// Integração PostgreSQL isolada via PGlite. Não conecta ao banco real.
const { PGlite } = require(process.env.CAMPAIGN_PGLITE_MODULE || '@electric-sql/pglite');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const admin = '11111111-1111-4111-8111-111111111111';
const user = '22222222-2222-4222-8222-222222222222';
(async () => {
    const db = new PGlite();
    try {
        await db.exec(`
            CREATE ROLE anon; CREATE ROLE authenticated;
            CREATE SCHEMA auth;
            CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$ SELECT nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
            GRANT USAGE ON SCHEMA auth, public TO authenticated, anon;
            GRANT EXECUTE ON FUNCTION auth.uid() TO authenticated, anon;
            CREATE TABLE profiles(id uuid PRIMARY KEY, role text NOT NULL);
            INSERT INTO profiles VALUES ('${admin}', 'admin'), ('${user}', 'cadastrador');
            CREATE TABLE cidadaos(id uuid PRIMARY KEY DEFAULT gen_random_uuid(), name text NOT NULL, user_id uuid NOT NULL,
                email text, dob date, sexo text, type text, leader uuid, cpf text UNIQUE, rg text, voterid text UNIQUE,
                zona text, secao text, phone text, whatsapp boolean, profissao text, cep text, logradouro text,
                numero text, complemento text, bairro text, cidade text, estado text, sons integer, daughters integer,
                children jsonb, localtrabalho text, nome_mae text, nome_pai text, photourl text,
                latitude double precision, longitude double precision, updated_at timestamptz, created_at timestamptz DEFAULT now());
            CREATE TABLE veiculos(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, cidadao_id uuid REFERENCES cidadaos(id),
                tipo text NOT NULL, placa text UNIQUE, modelo text, cor text, adesivado boolean NOT NULL DEFAULT false, created_at timestamptz DEFAULT now());
            ALTER TABLE profiles ENABLE ROW LEVEL SECURITY;
            ALTER TABLE cidadaos ENABLE ROW LEVEL SECURITY;
            ALTER TABLE veiculos ENABLE ROW LEVEL SECURITY;
            CREATE POLICY profile_own ON profiles FOR SELECT TO authenticated USING(id=auth.uid());
            CREATE POLICY citizen_visible ON cidadaos TO authenticated
                USING(user_id=auth.uid() OR EXISTS(SELECT 1 FROM profiles WHERE id=auth.uid() AND role='admin'))
                WITH CHECK(user_id=auth.uid() OR EXISTS(SELECT 1 FROM profiles WHERE id=auth.uid() AND role='admin'));
            CREATE POLICY vehicle_visible ON veiculos TO authenticated
                USING(EXISTS(SELECT 1 FROM cidadaos WHERE id=cidadao_id))
                WITH CHECK(EXISTS(SELECT 1 FROM cidadaos WHERE id=cidadao_id));
            GRANT SELECT ON profiles TO authenticated;
            GRANT SELECT, INSERT, UPDATE, DELETE ON cidadaos, veiculos TO authenticated;
            GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO authenticated;
        `);
        const migration = fs.readFileSync(path.join(__dirname, '../sql/001_salvamento_atomico.sql'), 'utf8');
        await db.exec(migration);
        await db.exec(migration); // reexecução idempotente
        await db.exec(`SET ROLE authenticated; SET request.jwt.claim.sub='${admin}';`);
        const save = async (id, citizen, vehicles) => (await db.query(
            'SELECT public.salvar_cidadao_com_veiculos_v2($1::uuid,$2::jsonb,$3::jsonb) AS id',
            [id, JSON.stringify(citizen), JSON.stringify(vehicles)]
        )).rows[0].id;
        const query = async (sql, args = []) => (await db.query(sql, args)).rows;
        const id = await save(null, { name: 'Pessoa teste', user_id: user, cpf: 'teste1', children: [{name: 'Filho'}] }, [
            { tipo: 'Carro', placa: 'AAA1A11', modelo: 'Original', adesivado: true },
            { tipo: 'Moto', placa: 'BBB2B22', adesivado: false }
        ]);
        let vehicles = await query('SELECT * FROM veiculos WHERE cidadao_id=$1 ORDER BY id', [id]);
        assert.equal(vehicles.length, 2);
        assert.equal((await query('SELECT user_id FROM cidadaos WHERE id=$1', [id]))[0].user_id, admin);
        const car = vehicles[0]; const moto = vehicles[1];
        await save(id, { name: 'Atualizado', user_id: user }, [{ ...car, modelo: 'Novo' }, moto]);
        vehicles = await query('SELECT * FROM veiculos WHERE cidadao_id=$1 ORDER BY id', [id]);
        assert.equal(vehicles[0].id, car.id); assert.equal(vehicles[0].modelo, 'Novo');
        assert.equal((await query('SELECT user_id FROM cidadaos WHERE id=$1', [id]))[0].user_id, admin);
        console.log('PASS: migração idempotente; criação e atualização preservam IDs e autoria.');

        await assert.rejects(save(id, { name: 'Não deve persistir' }, [{ ...car, placa: moto.placa }, moto]), /unique|duplicate/i);
        assert.equal((await query('SELECT name FROM cidadaos WHERE id=$1', [id]))[0].name, 'Atualizado');
        assert.equal((await query('SELECT placa FROM veiculos WHERE id=$1', [car.id]))[0].placa, car.placa);
        await assert.rejects(save(null, { name: 'Novo com falha' }, [{ tipo: 'Carro', placa: car.placa }]), /unique|duplicate/i);
        assert.equal((await query("SELECT count(*)::int AS n FROM cidadaos WHERE name='Novo com falha'"))[0].n, 0);
        console.log('PASS: erro de veículo reverte também o cidadão, na criação e na edição.');

        const otherId = await save(null, { name: 'Outra pessoa' }, [{ tipo: 'Carro', placa: 'CCC3C33', adesivado: false }]);
        const otherVehicle = (await query('SELECT * FROM veiculos WHERE cidadao_id=$1', [otherId]))[0];
        await assert.rejects(save(id, { name: 'Tentativa' }, [otherVehicle]), /não pertence/);
        assert.equal((await query('SELECT name FROM cidadaos WHERE id=$1', [id]))[0].name, 'Atualizado');
        await assert.rejects(save(id, { name: 'Tentativa' }, [car, car]), /repetido/);
        await assert.rejects(save(id, { name: 'Tentativa' }, [{ tipo: 'Caminhão' }]), /inválido/);
        console.log('PASS: veículo alheio, ID repetido e tipo inválido são recusados sem alteração parcial.');

        await save(id, { name: 'Atualizado' }, [{ ...car, modelo: 'Mantido' }]);
        vehicles = await query('SELECT * FROM veiculos WHERE cidadao_id=$1', [id]);
        assert.equal(vehicles.length, 1); assert.equal(vehicles[0].id, car.id);
        console.log('PASS: remoção exclui somente o veículo retirado do formulário.');

        await db.exec(`SET request.jwt.claim.sub='${user}';`);
        await assert.rejects(save(id, { name: 'Acesso indevido' }, []), /sem acesso/);
        const own = await save(null, { name: 'Próprio cadastrador', user_id: admin }, []);
        assert.equal((await query('SELECT user_id FROM cidadaos WHERE id=$1', [own]))[0].user_id, user);
        await db.exec(`SET request.jwt.claim.sub='${admin}';`);
        await save(own, { name: 'Editado pelo admin', user_id: admin }, []);
        assert.equal((await query('SELECT user_id FROM cidadaos WHERE id=$1', [own]))[0].user_id, user);
        console.log('PASS: RLS impede acesso a terceiros; edição por admin mantém autoria do cadastrador.');
        await db.exec("SET request.jwt.claim.sub='';");
        await assert.rejects(save(null, { name: 'Sem sessão' }, []), /Sessão expirada/);
        await db.exec('RESET ROLE; SET ROLE anon;');
        await assert.rejects(save(null, { name: 'Anônimo' }, []), /permission denied/);
        console.log('PASS: sessão ausente e role anônima não podem salvar.');
        await db.exec(`RESET ROLE;
            DROP POLICY vehicle_visible ON veiculos;
            CREATE POLICY v_read ON veiculos FOR SELECT TO authenticated USING(true);
            CREATE POLICY v_insert ON veiculos FOR INSERT TO authenticated WITH CHECK(true);
            CREATE POLICY v_update ON veiculos FOR UPDATE TO authenticated USING(true) WITH CHECK(true);
            SET ROLE authenticated; SET request.jwt.claim.sub='${admin}';`);
        await assert.rejects(save(id, { name: 'Remoção sem permissão' }, []), /Sem permissão para remover/);
        assert.equal((await query('SELECT name FROM cidadaos WHERE id=$1', [id]))[0].name, 'Atualizado');
        assert.equal((await query('SELECT count(*)::int AS n FROM veiculos WHERE cidadao_id=$1', [id]))[0].n, 1);
        console.log('PASS: exclusão bloqueada por RLS reverte o salvamento inteiro.');
    } finally { await db.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
